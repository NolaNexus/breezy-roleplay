#!/usr/bin/env bash
# Regenerate docs/scenarios.md from the scenario files in scenarios/.
#
# The index is derived data: it is deterministic, ordered by file name, and
# committed so the repository stays browsable on GitHub. CI re-runs this script
# and fails if the committed copy has drifted.

set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT_DIR"

exec python3 - <<'PY'
"""Build docs/scenarios.md from the Markdown files in scenarios/."""

from __future__ import annotations

import re
import sys
from pathlib import Path

SCENARIO_DIR = Path("scenarios")
OUTPUT = Path("docs/scenarios.md")

FIELD = re.compile(r"^\*\*(?P<key>[A-Za-z ]+):\*\*\s*(?P<value>.*)$")


def parse(path: Path) -> dict[str, str]:
    """Extract Title, Participants and Setting from one scenario file."""
    title = ""
    setting = ""
    participants: list[str] = []
    collecting_participants = False

    for raw_line in path.read_text(encoding="utf-8").splitlines():
        line = raw_line.strip()

        if collecting_participants:
            if line.startswith("- "):
                participants.append(line[2:].strip())
                continue
            collecting_participants = False

        match = FIELD.match(line)
        if match is None:
            continue

        key = match.group("key").strip().lower()
        value = match.group("value").strip()
        if key == "title":
            title = value
        elif key == "setting":
            setting = value
        elif key == "participants":
            collecting_participants = True

    return {
        "title": title or path.stem.replace("-", " ").title(),
        "participants": ", ".join(participants) or "-",
        "setting": setting or "-",
    }


def escape(cell: str) -> str:
    """Keep table cells on one line and escape the column separator."""
    return cell.replace("|", r"\|").replace("\n", " ").strip()


def render_table(headers: list[str], rows: list[list[str]]) -> list[str]:
    """Render a padded Markdown table so pipes line up in plain text."""
    widths = [len(header) for header in headers]
    for row in rows:
        for index, cell in enumerate(row):
            widths[index] = max(widths[index], len(cell))

    def line(cells: list[str]) -> str:
        padded = [cell.ljust(widths[index]) for index, cell in enumerate(cells)]
        return "| " + " | ".join(padded) + " |"

    separator = ["-" * width for width in widths]
    return [line(headers), line(separator), *(line(row) for row in rows)]


def main() -> int:
    files = sorted(SCENARIO_DIR.glob("*.md"))
    if not files:
        print("generate_scenario_index: no scenarios found", file=sys.stderr)
        return 1

    rows: list[list[str]] = []
    for path in files:
        data = parse(path)
        rows.append(
            [
                escape(data["title"]),
                escape(data["participants"]),
                escape(data["setting"]),
                path.as_posix(),
            ]
        )

    table = render_table(["Title", "Participants", "Setting", "File"], rows)

    document = "\n".join(
        [
            "# Scenario Index",
            "",
            "This document lists every role-play scenario in the repository. It is",
            "generated by `scripts/generate_scenario_index.sh` from the files in",
            "`scenarios/`; do not edit it by hand.",
            "",
            *table,
            "",
            f"_{len(files)} scenario(s). Add a Markdown file under `scenarios/` and run",
            "`make docs` to refresh this index._",
            "",
            "## Scenario Format",
            "",
            "Each scenario is plain Markdown with three fields the index reads:",
            "",
            "```markdown",
            "# Scenario Title",
            "",
            "**Title:** A short, human-readable title",
            "",
            "**Participants:**",
            "",
            "- First participant",
            "- Second participant",
            "",
            "**Setting:** Where the scene takes place",
            "",
            "**Scenario Outline:**",
            "",
            "1. First beat",
            "2. Second beat",
            "```",
            "",
            "See [`AGENTS.md`](../AGENTS.md) for the workflow that runs a scenario end",
            "to end.",
            "",
        ]
    )

    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(document, encoding="utf-8")
    print(f"generate_scenario_index: wrote {OUTPUT} ({len(files)} scenario(s))")
    return 0


sys.exit(main())
PY
